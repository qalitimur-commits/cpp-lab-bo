// Функция очистки потока ввода для защиты от невалидных данных
void clearInputStream() {
    cin.clear();
    cin.ignore(numeric_limits<streamsize>::max(), '\n');
}

// МОДУЛЬ 1: Учет рабочего времени
void runWorkTimeModule() {
    int days = 0;
    double rate = 0.0;
    double hoursPerDay = 0.0;

    cout << "\n========================================\n";
    cout << "   МОДУЛЬ 1: УЧЕТ РАБОЧЕГО ВРЕМЕНИ\n";
    cout << "========================================\n";

    while (true) {
        cout << "Введите количество рабочих дней в неделе (ожидается 5): ";
        if (cin >> days && days > 0) break;
        cout << "Ошибка! Введите корректное число.\n";
        clearInputStream();
    }

    while (true) {
        cout << "Введите ставку (ожидается 0.5): ";
        if (cin >> rate && rate > 0) break;
        cout << "Ошибка! Введите корректную ставку.\n";
        clearInputStream();
    }

    // Блокирующий цикл валидации часов
    do {
        cout << "Введите количество рабочих часов в день: ";
        if (!(cin >> hoursPerDay)) {
            cout << "Некорректный ввод! Попробуйте снова.\n";
            clearInputStream();
            continue;
        }

        double totalWeeklyHours = days * hoursPerDay;
        double normHours = 40.0 * rate; // 20 часов

        if (hoursPerDay == 2.0) {
            cout << "\nОшибка! При " << days << "-дневной рабочей неделе 2 часа в день составляют " 
                 << totalWeeklyHours << " часов в неделю. "
                 << "Дефицит рабочего времени: " << (normHours - totalWeeklyHours) 
                 << " часов (50% от нормы " << rate << " ставки). "
                 << "Налицо факт предоставления заведомо ложных сведений работодателю.\n\n";
        } else if (hoursPerDay != 4.0) {
            cout << "\nНеобходимо ввести и подтвердить норму в 4 часа в день!\n\n";
        } else {
            cout << "\nНорма рабочего времени (" << totalWeeklyHours << " ч/нед) успешно подтверждена.\n";
            break;
        }

    } while (true);
}

